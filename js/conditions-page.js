(function () {
  const backdrop = document.getElementById('condModal');
  const closeBtn = document.getElementById('condModalClose');
  const photo    = document.getElementById('condModalPhoto');
  const nameEl   = document.getElementById('condModalName');
  const descEl   = document.getElementById('condModalDesc');
  const descLabelEl = document.getElementById('condModalDescLabel');
  const detailLabelEl = document.getElementById('condModalDetailLabel');
  const detailEl = document.getElementById('condModalDetail');
  const noteEl   = document.getElementById('condModalNote');
  if (!backdrop) return;

  let lastFocused = null;

  function specRow(k, v) {
    var row = document.createElement('div'); row.className = 'cond-modal__spec';
    var ke = document.createElement('span'); ke.className = 'cond-modal__spec-k'; ke.textContent = k;
    var ve = document.createElement('span'); ve.className = 'cond-modal__spec-v'; ve.textContent = v;
    row.appendChild(ke); row.appendChild(ve); return row.outerHTML;
  }

  function openModal(slug) {
    const d = CONDITION_DATA[slug];
    if (!d) return;
    lastFocused = document.activeElement;
    nameEl.textContent = d.name;
    descEl.textContent = d.desc;
    photo.src = d.img;
    photo.alt = 'Custom orthotic for ' + d.name;
    if (d.specs) {
      descLabelEl.textContent = 'Overview';
      detailLabelEl.textContent = 'Specifications';
      detailEl.innerHTML = '<div class="cond-modal__specs">' + d.specs.filter(function (s) { return !(s[0] === 'Orthotic Width' && /^normal$/i.test(s[1])); }).map(function (s) { return specRow(s[0], s[1]); }).join('') + '</div>';
      noteEl.textContent = "Specifications reflect the standard build and can be tailored to the prescription. Final device selection is always the treating provider's clinical decision.";
    } else {
      descLabelEl.textContent = 'About this condition';
      detailLabelEl.textContent = 'Accommodations that help';
      detailEl.innerHTML = '<ul class="cond-modal__list">' + d.accs.map(function (a) {
        const li = document.createElement('li');
        li.textContent = a;
        return li.outerHTML;
      }).join('') + '</ul>';
      noteEl.textContent = "Commonly used orthotic features are shown for reference only. Final device selection is always the treating provider's clinical decision.";
    }
    backdrop.classList.add('is-open');
    document.body.style.overflow = 'hidden';
    closeBtn.focus();
  }

  function closeModal() {
    backdrop.classList.remove('is-open');
    document.body.style.overflow = '';
    if (lastFocused && typeof lastFocused.focus === 'function') lastFocused.focus();
  }

  document.querySelectorAll('.cond-card[data-slug]').forEach(function (card) {
    card.addEventListener('click', function () { openModal(card.dataset.slug); });
    card.addEventListener('keydown', function (e) {
      if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); openModal(card.dataset.slug); }
    });
  });

  closeBtn.addEventListener('click', closeModal);
  backdrop.addEventListener('click', function (e) { if (e.target === backdrop) closeModal(); });
  document.addEventListener('keydown', function (e) {
    if (backdrop.classList.contains('is-open') && e.key === 'Escape') closeModal();
  });
})();
